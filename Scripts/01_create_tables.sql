SET SQLBLANKLINES ON;

/* =========================================================
   SALES & PURCHASE MANAGEMENT SYSTEM
   Oracle Database
   Schema: SALESPURCHASEDB
   ========================================================= */

/* =========================
   1. tblEmployees
   ========================= */
CREATE TABLE tblEmployees (
    EmployeeID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EmployeeName    VARCHAR2(100) NOT NULL,
    UserName        VARCHAR2(50) NOT NULL,
    Password        VARCHAR2(255) NOT NULL,
    UserType        VARCHAR2(30),
    Role            VARCHAR2(50),
    JobTitle        VARCHAR2(100),
    Email           VARCHAR2(100),
    Phone           VARCHAR2(30),
    HomePhone       VARCHAR2(30),
    Address         VARCHAR2(255),
    City            VARCHAR2(100),
    StateProvince   VARCHAR2(100),
    ZipPostalCode   VARCHAR2(20),
    CountryRegion   VARCHAR2(100),
    Photo           BLOB,

    CONSTRAINT PK_tblEmployees
        PRIMARY KEY (EmployeeID),

    CONSTRAINT UQ_tblEmployees_UserName
        UNIQUE (UserName),

    CONSTRAINT UQ_tblEmployees_Email
        UNIQUE (Email)
);

/* =========================
   2. tblMembers
   ========================= */
CREATE TABLE tblMembers (
    MemberID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MemberName    VARCHAR2(100) NOT NULL,
    Discount      NUMBER(5,2) DEFAULT 0,

    CONSTRAINT PK_tblMembers
        PRIMARY KEY (MemberID),

    CONSTRAINT CK_tblMembers_Discount
        CHECK (Discount BETWEEN 0 AND 100)
);

/* =========================
   3. tblCustomers
   ========================= */
CREATE TABLE tblCustomers (
    CustomerID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CustomerName    VARCHAR2(100) NOT NULL,
    JobTitle        VARCHAR2(100),
    Phone           VARCHAR2(30),
    Email           VARCHAR2(100),
    Address         VARCHAR2(255),
    MemberID        NUMBER,

    CONSTRAINT PK_tblCustomers
        PRIMARY KEY (CustomerID),

    CONSTRAINT FK_Customers_Members
        FOREIGN KEY (MemberID)
        REFERENCES tblMembers(MemberID)
);

/* =========================
   4. tblCategories
   ========================= */
CREATE TABLE tblCategories (
    CategoryID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CategoryName    VARCHAR2(100) NOT NULL,
    Description     VARCHAR2(500),
    CreatedDate     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy       NUMBER,
    UpdateDate      TIMESTAMP,
    UpdateBy        NUMBER,

    CONSTRAINT PK_tblCategories
        PRIMARY KEY (CategoryID),

    CONSTRAINT UQ_tblCategories_Name
        UNIQUE (CategoryName),

    CONSTRAINT FK_Categories_CreatedBy
        FOREIGN KEY (CreatedBy)
        REFERENCES tblEmployees(EmployeeID),

    CONSTRAINT FK_Categories_UpdateBy
        FOREIGN KEY (UpdateBy)
        REFERENCES tblEmployees(EmployeeID)
);

/* =========================
   5. tblProducts
   ========================= */
CREATE TABLE tblProducts (
    ProductID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ProductName     VARCHAR2(150) NOT NULL,
    Description     VARCHAR2(500),
    CategoryID      NUMBER NOT NULL,
    Barcode         VARCHAR2(100),
    ExpiryDate      DATE,
    Qty             NUMBER DEFAULT 0 NOT NULL,
    UnitPriceIn     NUMBER(12,2) DEFAULT 0 NOT NULL,
    UnitPriceOut    NUMBER(12,2) DEFAULT 0 NOT NULL,
    ProductImage    BLOB,
    isDeleted       NUMBER(1) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_tblProducts
        PRIMARY KEY (ProductID),

    CONSTRAINT FK_Products_Categories
        FOREIGN KEY (CategoryID)
        REFERENCES tblCategories(CategoryID),

    CONSTRAINT UQ_tblProducts_Barcode
        UNIQUE (Barcode),

    CONSTRAINT CK_tblProducts_Qty
        CHECK (Qty >= 0),

    CONSTRAINT CK_tblProducts_PriceIn
        CHECK (UnitPriceIn >= 0),

    CONSTRAINT CK_tblProducts_PriceOut
        CHECK (UnitPriceOut >= 0),

    CONSTRAINT CK_tblProducts_IsDeleted
        CHECK (isDeleted IN (0,1))
);

/* =========================
   6. tblSuppliers
   ========================= */
CREATE TABLE tblSuppliers (
    SupplierID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SupplierName    VARCHAR2(100) NOT NULL,
    JobTitle        VARCHAR2(100),
    CompanyName     VARCHAR2(150),
    Phone           VARCHAR2(30),
    Email           VARCHAR2(100),
    Address         VARCHAR2(255),
    Country         VARCHAR2(100),
    Website         VARCHAR2(255),

    CONSTRAINT PK_tblSuppliers
        PRIMARY KEY (SupplierID)
);

/* =========================
   7. tblShippers
   ========================= */
CREATE TABLE tblShippers (
    ShipperID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CompanyName     VARCHAR2(150) NOT NULL,
    ContactName     VARCHAR2(100),
    ContactNumber   VARCHAR2(30),
    Email           VARCHAR2(100),
    Address         VARCHAR2(255),
    Country         VARCHAR2(100),

    CONSTRAINT PK_tblShippers
        PRIMARY KEY (ShipperID)
);

/* =========================
   8. tblSales
   ========================= */
CREATE TABLE tblSales (
    SalesID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EmployeeID      NUMBER NOT NULL,
    CustomerID      NUMBER,
    SalesDate       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_tblSales
        PRIMARY KEY (SalesID),

    CONSTRAINT FK_Sales_Employees
        FOREIGN KEY (EmployeeID)
        REFERENCES tblEmployees(EmployeeID),

    CONSTRAINT FK_Sales_Customers
        FOREIGN KEY (CustomerID)
        REFERENCES tblCustomers(CustomerID)
);

/* =========================
   9. tblSalesDetails
   ========================= */
CREATE TABLE tblSalesDetails (
    SalesID         NUMBER NOT NULL,
    ProductID       NUMBER NOT NULL,
    QtySales        NUMBER NOT NULL,

    CONSTRAINT PK_tblSalesDetails
        PRIMARY KEY (SalesID, ProductID),

    CONSTRAINT FK_SalesDetails_Sales
        FOREIGN KEY (SalesID)
        REFERENCES tblSales(SalesID)
        ON DELETE CASCADE,

    CONSTRAINT FK_SalesDetails_Products
        FOREIGN KEY (ProductID)
        REFERENCES tblProducts(ProductID),

    CONSTRAINT CK_SalesDetails_Qty
        CHECK (QtySales > 0)
);

/* =========================
   10. tblPurchase
   ========================= */
CREATE TABLE tblPurchase (
    PurchaseID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EmployeeID      NUMBER NOT NULL,
    SupplierID      NUMBER NOT NULL,
    ShipperID       NUMBER,
    PurchaseDate    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_tblPurchase
        PRIMARY KEY (PurchaseID),

    CONSTRAINT FK_Purchase_Employees
        FOREIGN KEY (EmployeeID)
        REFERENCES tblEmployees(EmployeeID),

    CONSTRAINT FK_Purchase_Suppliers
        FOREIGN KEY (SupplierID)
        REFERENCES tblSuppliers(SupplierID),

    CONSTRAINT FK_Purchase_Shippers
        FOREIGN KEY (ShipperID)
        REFERENCES tblShippers(ShipperID)
);

/* =========================
   11. tblPurchaseDetails
   ========================= */
CREATE TABLE tblPurchaseDetails (
    PurchaseID      NUMBER NOT NULL,
    ProductID       NUMBER NOT NULL,
    PurchaseQty     NUMBER NOT NULL,

    CONSTRAINT PK_tblPurchaseDetails
        PRIMARY KEY (PurchaseID, ProductID),

    CONSTRAINT FK_PurchaseDetails_Purchase
        FOREIGN KEY (PurchaseID)
        REFERENCES tblPurchase(PurchaseID)
        ON DELETE CASCADE,

    CONSTRAINT FK_PurchaseDetails_Product
        FOREIGN KEY (ProductID)
        REFERENCES tblProducts(ProductID),

    CONSTRAINT CK_PurchaseDetails_Qty
        CHECK (PurchaseQty > 0)
);

COMMIT;
